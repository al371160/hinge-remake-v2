function photo(id: string, url: string, alt: string, extra?: Partial<Photo>): Photo {
  return {
    id,
    url: url.includes('?') ? url : `${url}?auto=format&fit=crop&w=800&h=1000&q=70`,
    alt,
    kind: extra?.kind ?? 'photo',
    ...extra,
  }
}

function personPhotos(
  who: Parameters<typeof faceUrls>[0],
  idPrefix: string,
  extras?: Array<Partial<Photo> | undefined>,
): Photo[] {
  return faceUrls(who).map((url, i) => photo(`${idPrefix}-p${i + 1}`, url, idPrefix, extras?.[i]))
}

